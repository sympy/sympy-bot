from ..pr_template import validate_pr_template

valid_PR_description = """\
#### References to other Issues or PRs

Fixes #1234

#### Brief description of what is fixed or changed

Added new trig solvers.

#### Other comments

#### AI Generation Disclosure

<!-- If this pull request includes AI-generated code or text, please disclose
the tool used and specify which lines were generated. -->

NO AI USE

#### Release Notes

<!-- BEGIN RELEASE NOTES -->
* solvers
  * new trig solvers
<!-- END RELEASE NOTES -->
"""

valid_PR_description_ai_disclosure = valid_PR_description.replace(
    'NO AI USE', 'The code in solvers/trig.py was generated by an LLM.')

# The AI section contains only the template comment, nothing else
invalid_PR_description_blank_ai = valid_PR_description.replace('NO AI USE', '')

invalid_PR_description_missing_sections = """\
#### Brief description of what is fixed or changed

Added new trig solvers.

#### Release Notes

<!-- BEGIN RELEASE NOTES -->
* solvers
  * new trig solvers
<!-- END RELEASE NOTES -->
"""

def test_valid():
    status, messages = validate_pr_template(valid_PR_description, 'Added new trig solvers')
    assert status is True
    assert messages == []

def test_valid_ai_disclosure():
    status, messages = validate_pr_template(valid_PR_description_ai_disclosure, 'Added new trig solvers')
    assert status is True
    assert messages == []

def test_missing_sections():
    status, messages = validate_pr_template(invalid_PR_description_missing_sections, 'Added new trig solvers')
    assert status is False
    assert len(messages) == 1
    assert '#### References to other Issues or PRs' in messages[0]
    assert '#### Other comments' in messages[0]
    assert '#### AI Generation Disclosure' in messages[0]
    assert '#### Brief description of what is fixed or changed' not in messages[0]
    assert '#### Release Notes' not in messages[0]

def test_blank_ai_disclosure():
    status, messages = validate_pr_template(invalid_PR_description_blank_ai, 'Added new trig solvers')
    assert status is False
    assert len(messages) == 1
    assert 'AI Generation Disclosure' in messages[0]
    assert 'NO AI USE' in messages[0]

def test_issue_number_in_title():
    status, messages = validate_pr_template(valid_PR_description, 'Added new trig solvers (fixes #1234)')
    assert status is False
    assert len(messages) == 1
    assert 'title' in messages[0]

def test_empty_body():
    status, messages = validate_pr_template('', 'Added new trig solvers')
    assert status is False
    assert len(messages) == 1
    for section in ['#### References to other Issues or PRs',
                    '#### Brief description of what is fixed or changed',
                    '#### Other comments',
                    '#### AI Generation Disclosure',
                    '#### Release Notes']:
        assert section in messages[0]

def test_none_body_and_title():
    status, messages = validate_pr_template(None, None)
    assert status is False
    assert len(messages) == 1

def test_multiple_problems():
    status, messages = validate_pr_template(invalid_PR_description_blank_ai, 'Fixes #1234')
    assert status is False
    assert len(messages) == 2
