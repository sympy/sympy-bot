from ..pr_template import validate_pr_template, AI_DISCLOSURE_HEADING

valid_PR_description = """\
#### References to other Issues or PRs

Fixes #1234

#### Brief description of what is fixed or changed

Added new trig solvers.

#### Other comments

#### AI Generation Disclosure

<!-- If this pull request includes AI-generated code or text, please disclose
the tool used and specify which lines were generated. -->

NO AI USE

#### Release Notes

<!-- BEGIN RELEASE NOTES -->
* solvers
  * new trig solvers
<!-- END RELEASE NOTES -->
"""

valid_PR_description_ai_disclosure = valid_PR_description.replace(
    'NO AI USE', 'The code in solvers/trig.py was generated by an LLM.')

# The AI section contains only the template comment, nothing else
blank_ai_PR_description = valid_PR_description.replace('NO AI USE', '')

# The AI section is the last thing in the description, with no #### heading
# after it to terminate it
trailing_ai_PR_description = """\
#### Brief description of what is fixed or changed

Added new trig solvers.

#### AI Generation Disclosure

NO AI USE
"""

def test_valid():
    assert validate_pr_template(valid_PR_description) == (True, [])

def test_valid_ai_disclosure():
    assert validate_pr_template(valid_PR_description_ai_disclosure) == (True, [])

def test_valid_ai_section_last():
    assert validate_pr_template(trailing_ai_PR_description) == (True, [])

def test_other_sections_are_not_required():
    # Only the AI disclosure section is required. Deleting the rest of the
    # template is not something the bot complains about.
    status, messages = validate_pr_template(
        '#### AI Generation Disclosure\n\nNO AI USE\n')
    assert status is True
    assert messages == []

def test_blank_ai_disclosure():
    status, messages = validate_pr_template(blank_ai_PR_description)
    assert status is False
    assert len(messages) == 1
    assert 'must not be left blank' in messages[0]
    assert 'NO AI USE' in messages[0]

def test_missing_ai_disclosure():
    status, messages = validate_pr_template(
        valid_PR_description.replace(AI_DISCLOSURE_HEADING, '#### Something else'))
    assert status is False
    assert len(messages) == 1
    assert 'is missing' in messages[0]

def test_empty_body():
    status, messages = validate_pr_template('')
    assert status is False
    assert len(messages) == 1
    assert 'is missing' in messages[0]

def test_none_body():
    # GitHub sends body: null for a pull request opened with no description
    status, messages = validate_pr_template(None)
    assert status is False
    assert len(messages) == 1
    assert 'is missing' in messages[0]

def test_heading_must_be_on_its_own_line():
    # A mention of the heading in prose is not the section itself
    status, messages = validate_pr_template(
        f'I removed the `{AI_DISCLOSURE_HEADING}` section.\n')
    assert status is False
    assert len(messages) == 1
    assert 'is missing' in messages[0]

def test_heading_surrounding_whitespace():
    status, messages = validate_pr_template(
        '  #### AI Generation Disclosure  \n\nNO AI USE\n')
    assert status is True
    assert messages == []

def test_blank_ai_disclosure_before_release_notes_block():
    # The "#### Release Notes" heading has been deleted, so the release notes
    # block directly follows a blank disclosure section. It should not count as
    # filling the section in.
    status, messages = validate_pr_template("""\
#### AI Generation Disclosure

<!-- If this pull request includes AI-generated code or text, please disclose
the tool used. -->

<!-- BEGIN RELEASE NOTES -->
* solvers
  * new trig solvers
<!-- END RELEASE NOTES -->
""")
    assert status is False
    assert len(messages) == 1
    assert 'must not be left blank' in messages[0]
