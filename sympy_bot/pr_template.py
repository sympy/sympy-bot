#!/usr/bin/env python
"""
Validate that a pull request description follows the SymPy pull request
template.

This is a pure module (no I/O, no network, no async), mirroring the style of
``get_changelog`` in ``changelog.py``: a plain string goes in and a
``(status, message)`` tuple comes out.

The checks are intentionally kept as small, independent functions collected in
``CHECKS``.  Each one takes the (already normalized) description and returns
``(ok, message_lines)``.  To add a new reason for rejecting a description, write
another check function and append it to ``CHECKS`` -- nothing else needs to
change.
"""
import re

# The full canonical SymPy pull request template. This is the single source of
# truth for this module. To update the checks when the upstream template
# changes, replace the text below with the new contents of
# https://github.com/sympy/sympy/blob/master/.github/PULL_REQUEST_TEMPLATE.md
PR_TEMPLATE = '''\
<!-- DO NOT DELETE OR REPLACE THIS TEMPLATE or the PR will be closed.

Read our Policy on AI Generated Code and Communication at
https://docs.sympy.org/dev/contributing/ai-generated-code-policy.html.

As required in the policy do not use AI-generated text to complete the PR
description below or the PR will be closed. Follow the instructions in the
template below and keep all section headings or the PR will be closed.

The PR title above should be a short description of what was changed. Do not
include the issue number in the title. -->

#### References to other Issues or PRs

<!-- If there is an issue related to this PR, include a link to the issue here.
It is important not to waste reviewer's time by skipping this section.

If this pull request fixes an issue, write "Fixes #NNNN" in that exact format,
e.g. "Fixes #1234" (see https://tinyurl.com/auto-closing for more information).

If this does not completely fix the issue, then write "See #NNNN" or "partially
fixes #NNNN", e.g. "See #1234" or "partially fixes #1234". -->


#### Brief description of what is fixed or changed


#### Other comments


#### AI Generation Disclosure

<!-- If this pull request includes AI-generated code or text, please disclose
the tool used and specify which lines were generated. Disclosure is not
required for minor assistive tasks, such as spell-checking or code reviewing,
in primarily human-authored work. Otherwise, write "NO AI USE" in the text area
below.

DO NOT just delete this AI section of the PR template and do not leave this
blank, or the PR will be closed. If you write "NO AI USE" and the code looks
like it was generated by AI then the PR will be closed. -->


#### Release Notes

<!-- Write the release notes for this release below between the BEGIN and END
statements. The basic format is a bulleted list with the name of the subpackage
and the release note for this PR. For example:

* solvers
  * Added a new solver for logarithmic equations.

* functions
  * Fixed a bug with log of integers. Formerly, `log(-x)` incorrectly gave `-log(x)`.

* physics.units
  * Corrected a semantical error in the conversion between volt and statvolt which
    reported the volt as being larger than the statvolt.

or if no release note(s) should be included use:

NO ENTRY

See https://github.com/sympy/sympy/wiki/Writing-Release-Notes for more
information on how to write release notes. The bot will check your release
notes automatically to see if they are formatted correctly. -->

<!-- BEGIN RELEASE NOTES -->

<!-- END RELEASE NOTES -->
'''

TEMPLATE_URL = "https://github.com/sympy/sympy/blob/master/.github/PULL_REQUEST_TEMPLATE.md"

# The section headings that must appear in the description, in template order.
# Each must be kept verbatim, as ``#### <heading>``: changing the heading level
# or its wording counts as missing (the template must not be altered).
REQUIRED_HEADINGS = [
    "References to other Issues or PRs",
    "Brief description of what is fixed or changed",
    "Other comments",
    "AI Generation Disclosure",
    "Release Notes",
]

# The subset of the required headings whose section body must contain
# author-provided content (after HTML comments are stripped out). The other
# headings only need to be present -- they may be empty. Release Notes content
# is validated separately by ``get_changelog``, so it is not required here.
CONTENT_REQUIRED_HEADINGS = [
    "Brief description of what is fixed or changed",
    "AI Generation Disclosure",
]

_COMMENT_RE = re.compile(r'<!--.*?-->', re.DOTALL)
# The start of any markdown heading, used to find where a section ends.
_HEADING_RE = re.compile(r'^#{1,6}[ \t]', re.MULTILINE)

# Every HTML comment that ships in the template must remain in the description,
# byte-for-byte. The template instructs authors not to delete or replace these
# ("DO NOT DELETE OR REPLACE THIS TEMPLATE"): rewriting or removing them is
# treated as a signal that the description may have been AI-generated rather
# than written by the author, so we require each one to be present verbatim.
# Derived from PR_TEMPLATE so the two can never drift apart.
REQUIRED_TEMPLATE_COMMENTS = _COMMENT_RE.findall(PR_TEMPLATE)


def _strip_comments(text):
    return _COMMENT_RE.sub('', text)


def _heading_marker(heading):
    return "#### " + heading


def _section_body(pr_desc, heading):
    """
    Return the text between ``#### <heading>`` and the next heading, or None if
    the heading isn't present verbatim.
    """
    marker = _heading_marker(heading)
    idx = pr_desc.find(marker)
    if idx == -1:
        return None
    after = pr_desc[idx + len(marker):]
    # Drop the rest of the heading line, then stop at the next heading.
    newline = after.find('\n')
    if newline == -1:
        return ''
    after = after[newline + 1:]
    nxt = _HEADING_RE.search(after)
    return after[:nxt.start()] if nxt else after


def _comment_label(comment):
    """A short, single-line label identifying a template comment in a message."""
    collapsed = ' '.join(comment.split())
    if len(collapsed) <= 70:
        return collapsed
    return collapsed[:67].rstrip() + '...'


def check_required_headings(pr_desc):
    """Every required section heading must be present, verbatim."""
    missing = [h for h in REQUIRED_HEADINGS if _heading_marker(h) not in pr_desc]
    if not missing:
        return True, []
    lines = [
        "* The following required section headings are missing from the pull request description:",
        "",
    ]
    lines += [f"  * `#### {h}`" for h in missing]
    lines += [
        "",
        f"  Please restore them from the [pull request template]({TEMPLATE_URL}). All of the section headings must be kept.",
    ]
    return False, lines


def check_required_template_comments(pr_desc):
    """Every HTML comment from the template must be kept, unmodified."""
    missing = [c for c in REQUIRED_TEMPLATE_COMMENTS if c not in pr_desc]
    if not missing:
        return True, []
    lines = [
        "* Some of the template's HTML comments are missing or were modified. Please keep all of the template comments exactly as they appear in the template (do not delete or rewrite them). The following are missing:",
        "",
    ]
    lines += [f"  * `{_comment_label(c)}`" for c in missing]
    lines += [
        "",
        f"  You can copy the original comments from the [pull request template]({TEMPLATE_URL}).",
    ]
    return False, lines


def check_required_content(pr_desc):
    """Content-required sections must be non-empty (ignoring HTML comments)."""
    empty = []
    for h in CONTENT_REQUIRED_HEADINGS:
        body = _section_body(pr_desc, h)
        if body is None:
            # A missing heading is already reported by check_required_headings.
            continue
        if not _strip_comments(body).strip():
            empty.append(h)
    if not empty:
        return True, []
    lines = [
        "* The following sections are required but are empty. Please fill them out:",
        "",
    ]
    lines += [f"  * `#### {h}`" for h in empty]
    return False, lines


# The list of checks a description must pass. Append to this to add new rules.
CHECKS = [
    check_required_headings,
    check_required_template_comments,
    check_required_content,
]


def validate_pr_template(pr_desc):
    """
    Check whether ``pr_desc`` follows the SymPy pull request template.

    ``pr_desc`` is the pull request description as a string (``None`` is treated
    as an empty description).

    Returns a tuple ``(status, message)`` where:

    - ``status`` is a boolean that is ``True`` when the description follows the
      template.
    - ``message`` is a markdown string explaining what is wrong. It is empty
      when ``status`` is ``True``.
    """
    if pr_desc is None:
        pr_desc = ''

    status = True
    message_lines = []
    for check in CHECKS:
        ok, lines = check(pr_desc)
        if not ok:
            status = False
            message_lines += lines

    return status, '\n'.join(message_lines)
